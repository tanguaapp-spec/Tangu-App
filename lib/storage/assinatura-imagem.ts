export type TipoImagemAceito = 'image/jpeg' | 'image/png' | 'image/webp' | 'image/gif'

export const EXTENSAO_POR_TIPO: Record<TipoImagemAceito, string> = {
  'image/jpeg': 'jpg',
  'image/png': 'png',
  'image/webp': 'webp',
  'image/gif': 'gif',
}

/**
 * Descobre o tipo real pelos primeiros bytes (assinatura do formato) — não
 * confia na extensão nem no Content-Type mandado pelo navegador. SVG fica de
 * fora de propósito: pode carregar script.
 */
export function detectarTipoImagem(b: Uint8Array): TipoImagemAceito | null {
  if (b.length < 12) return null
  if (b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff) return 'image/jpeg'
  if (b[0] === 0x89 && b[1] === 0x50 && b[2] === 0x4e && b[3] === 0x47 && b[4] === 0x0d && b[5] === 0x0a && b[6] === 0x1a && b[7] === 0x0a)
    return 'image/png'
  if (b[0] === 0x52 && b[1] === 0x49 && b[2] === 0x46 && b[3] === 0x46 && b[8] === 0x57 && b[9] === 0x45 && b[10] === 0x42 && b[11] === 0x50)
    return 'image/webp'
  if (b[0] === 0x47 && b[1] === 0x49 && b[2] === 0x46 && b[3] === 0x38 && (b[4] === 0x37 || b[4] === 0x39) && b[5] === 0x61)
    return 'image/gif'
  return null
}
